# Tokens that are valid words in both languages and therefore evidence for neither:
#   "me"  — English pronoun / romanized Hindi "में" (in)
#   "to"  — English preposition / romanized Hindi "तो" (then, so)
#   "the" — English article / romanized Hindi "थे" (they were)
# Assigning them to one side would be arbitrary and would bias every short utterance containing
# one. They are excluded from both counts instead, and the exclusion is asserted by a test so the
# two lists cannot drift back into overlapping.
AMBIGUOUS_TOKENS: frozenset[str] = frozenset({"me", "to", "the"})

HINDI_ONLY: frozenset[str] = HINDI_FUNCTION_WORDS - AMBIGUOUS_TOKENS
ENGLISH_ONLY: frozenset[str] = ENGLISH_FUNCTION_WORDS - AMBIGUOUS_TOKENS
