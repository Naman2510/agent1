"""Word lists for romanized-language identification.

Why function words and not content words: in code-switched Indian speech the *content* is
routinely English even when the sentence is Hindi — "Bhai KVL basically kya bol raha hai" is a
Hindi sentence with three English tokens in it. What stays Hindi is the grammatical scaffolding:
copulas, postpositions, pronouns, question words, light verbs. So the signal lives there.

Spelling is not standardised for romanized Hindi, so common variants are listed explicitly
(`kyun`/`kyon`/`kyu`, `nahi`/`nahin`, `theek`/`thik`). This is the direct cause of the WER
instability recorded in [EVALUATION.md §3.1] and the reason this module is a list rather than a
stemmer.

**Provenance:** hand-curated from high-frequency Hindi function words. Not derived from a corpus,
not frequency-weighted, and not validated against one — see the bias note in DATASET.md and the
accuracy baseline in EVALUATION.md before trusting it.
"""

