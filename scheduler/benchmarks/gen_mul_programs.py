#!/usr/bin/env python3
"""
gen_mul_programs.py -- generate CPU-only dot-product and matrix-multiply
kernels that use the hardware RV32M MUL instruction (available on a
core built with ENABLE_MUL=1, see docs/rv32m_mul.md) instead of the
software `mul32` shift-and-add routine every earlier phase had to use.

Not re-derived: each program is the already-verified Phase 13 template
from scheduler/benchmarks/gen_scheduler_programs.py (gen_cpu_dot /
gen_cpu_matmul) with exactly one substitution --

    jal  x1, mul32      ->      mul  x10, x11, x12

-- which is semantically the same operation at that call site: `mul32`
returns x10 = x11 * x12 (low 32 bits) and every caller only consumes
x10 afterwards. The now-unreachable `mul32` subroutine is then removed.
Both edits are asserted to match exactly once, so a template change
upstream fails loudly here instead of producing a subtly different
kernel. vecadd needs no variant (it never multiplies), and the
accelerator-driven programs are unchanged.

Sizes cover every workload with real measured data so far (Phase 13
training, Phase 14 held-out, scheduler-v2 round-2 held-out):
dot N in {1,2,3,4,6,8,12,16,32,64}, matmul N in {1,2,4,8}.

Writes sim/programs/scheduler/cpu_{dot,matmul}_mul_n{N}.s

Usage:
    python3 scheduler/benchmarks/gen_mul_programs.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "sim", "programs", "scheduler")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_scheduler_programs import gen_cpu_dot, gen_cpu_matmul  # noqa: E402

DOT_SIZES = [1, 2, 3, 4, 6, 8, 12, 16, 32, 64]
MATMUL_SIZES = [1, 2, 4, 8]

CALL = "    jal  x1, mul32\n"
HW_MUL = "    mul  x10, x11, x12\n"
MUL32_ROUTINE = re.compile(r"\nmul32:\n(?:.*\n)*?    ret\n")


def to_hw_mul(src, name):
    if src.count(CALL) != 1:
        raise ValueError(f"{name}: expected exactly one `{CALL.strip()}`, found {src.count(CALL)}")
    src = src.replace(CALL, HW_MUL)
    routines = MUL32_ROUTINE.findall(src)
    if len(routines) != 1:
        raise ValueError(f"{name}: expected exactly one mul32 routine, found {len(routines)}")
    src = MUL32_ROUTINE.sub("\n", src)
    leftover = [l for l in src.splitlines() if "mul32" in l and not l.lstrip().startswith("#")]
    if leftover:
        raise ValueError(f"{name}: mul32 still referenced in code: {leftover}")
    header = (f"# {name}.s -- generated by scheduler/benchmarks/gen_mul_programs.py: the\n"
              f"# Phase 13 template below with `jal x1, mul32` replaced by the hardware\n"
              f"# RV32M `mul x10, x11, x12` (needs a core built with ENABLE_MUL=1).\n")
    return header + src


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for op, gen, sizes in (("dot", gen_cpu_dot, DOT_SIZES), ("matmul", gen_cpu_matmul, MATMUL_SIZES)):
        for n in sizes:
            name = f"cpu_{op}_mul_n{n}"
            path = os.path.join(OUT_DIR, f"{name}.s")
            with open(path, "w") as f:
                f.write(to_hw_mul(gen(n), name))
            written.append(path)
    print(f"Wrote {len(written)} program(s) to {os.path.relpath(OUT_DIR, ROOT)}")


if __name__ == "__main__":
    main()
