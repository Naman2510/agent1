#!/usr/bin/env python3
"""
gen_scheduler_programs.py -- Phase 13: generate CPU-only and
accelerator-driven vecadd/dot/matmul benchmark programs at several
problem sizes, to build a real, measured training dataset for the AI
workload scheduler (Phase 13+). This EXTENDS Phase 11's single-size
benchmark (N=16 vecadd/dot, N=4 matmul) with two more sizes per
operation (smallest and largest reasonable), reusing the exact
verified register allocation and structure of Phase 11's
sim/programs/benchmarks/{cpu,accel}_{vecadd,dot,matmul}_bench.s files
-- these templates are NOT independently re-derived; they are the same
programs with only the size-dependent literal(s) parameterized.

Why generation instead of hand-writing more .s files: Phase 11 already
found one real bug (a register conflict) from hand-writing similar
files independently; a single, careful template generating every size
variant is safer -- one place to get the structure right, rather than
six-times-N places to introduce a copy-paste mistake in.

Why matmul needs special handling: vecadd/dot's loop body doesn't
depend on N at all (only the loop *bound* changes), so those two are
directly parameterizable. matmul's setup/compute loops compute a
flattened row-major index via `i*N` -- Phase 11's N=4 version
hardcodes this as a `slli ..., 2` (i<<2 == i*4 only because N
happened to be 4). This generator computes the correct shift amount
as log2(N) for each requested N, and restricts matmul sizes to powers
of two specifically so that "multiply by N" can stay a single `slli`
(matching Phase 11's real, already-verified hardware timing) instead
of introducing a software multiply into the address-computation path,
which would change what's actually being measured.

Every generated program is verified against Python-computed expected
values by scheduler/benchmarks/verify_scheduler_programs.py BEFORE any
of its measured cycle counts are trusted for training -- see that
script and docs/scheduler.md.

Usage:
    python3 scheduler/benchmarks/gen_scheduler_programs.py
"""

import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "sim", "programs", "scheduler")

# Sizes to generate IN ADDITION to Phase 11's existing N=16 (vecadd/dot)
# and N=4 (matmul), which are reused as-is (not regenerated) to avoid
# a second, possibly-diverging copy of an already-verified program.
# N=1 included specifically to check for a real CPU-wins crossover at
# the smallest possible workload (where the accelerator's fixed MMIO/
# polling overhead might not be worth paying) -- see docs/scheduler.md
# for what was actually found, not assumed.
VECADD_DOT_EXTRA_SIZES = [1, 4, 64]  # smallest possible, smallest useful, MAX_LEN
MATMUL_EXTRA_SIZES = [2, 8]           # smallest useful, and MAX_DIM (largest)


def gen_cpu_vecadd(n):
    return f"""\
# cpu_vecadd_n{n}.s -- Phase 13 scheduler dataset: CPU-only vector add,
# N={n}. Generated by scheduler/benchmarks/gen_scheduler_programs.py
# from the exact structure of sim/programs/benchmarks/cpu_vecadd_bench.s
# (Phase 11) -- see that file and docs/scheduler.md for the full
# rationale; only the loop bound N differs.

    li   x1, 0x1000
    li   x2, 0x2000
    li   x3, 0x3000
    li   x9, {n}
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF

    li   x4, 0
setup_loop:
    addi x5, x4, 1
    slli x6, x4, 2
    add  x7, x1, x6
    sw   x5, 0(x7)
    addi x8, x4, 2
    add  x7, x2, x6
    sw   x8, 0(x7)
    addi x4, x4, 1
    bne  x4, x9, setup_loop

    li   x4, 0
compute_loop:
    slli x6, x4, 2
    add  x7, x1, x6
    lw   x5, 0(x7)
    add  x7, x2, x6
    lw   x8, 0(x7)
    add  x5, x5, x8
    add  x7, x3, x6
    sw   x5, 0(x7)
    addi x4, x4, 1
    bne  x4, x9, compute_loop

    sw   x30, 0(x29)
done:
    j    done
"""


def gen_cpu_dot(n):
    return f"""\
# cpu_dot_n{n}.s -- Phase 13 scheduler dataset: CPU-only dot product,
# N={n}. Generated from sim/programs/benchmarks/cpu_dot_bench.s's
# structure (Phase 11); only the loop bound N differs. Uses the mul32
# software multiply routine (see mul32_test.s), and keeps &A[0] in
# x23, NOT x1, for the same real reason documented in
# cpu_dot_bench.s's header comment (x1 is jal's return-address
# register; a real bug from this exact mistake is in CHANGELOG.md's
# Phase 11 entry).

    li   x23, 0x1000
    li   x2,  0x2000
    li   x9,  {n}
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF
    li   x20, 0

    li   x4, 0
setup_loop:
    addi x5, x4, 1
    slli x6, x4, 2
    add  x7, x23, x6
    sw   x5, 0(x7)
    addi x8, x4, 2
    add  x7, x2, x6
    sw   x8, 0(x7)
    addi x4, x4, 1
    bne  x4, x9, setup_loop

    li   x4, 0
compute_loop:
    slli x6, x4, 2
    add  x7, x23, x6
    lw   x11, 0(x7)
    add  x7, x2, x6
    lw   x12, 0(x7)
    jal  x1, mul32
    add  x20, x20, x10
    addi x4, x4, 1
    bne  x4, x9, compute_loop

    sw   x30, 0(x29)
    j    done

mul32:
    li   x10, 0
    mv   x5, x11
    mv   x6, x12
mul32_loop:
    beq  x6, x0, mul32_done
    andi x7, x6, 1
    beq  x7, x0, mul32_skip
    add  x10, x10, x5
mul32_skip:
    slli x5, x5, 1
    srli x6, x6, 1
    j    mul32_loop
mul32_done:
    ret

done:
    j done
"""


def gen_cpu_matmul(n):
    shift = int(math.log2(n))
    assert 1 << shift == n, f"matmul N={n} must be a power of 2"
    return f"""\
# cpu_matmul_n{n}.s -- Phase 13 scheduler dataset: CPU-only {n}x{n}
# matrix multiply. Generated from
# sim/programs/benchmarks/cpu_matmul_bench.s's structure (Phase 11);
# the loop bound N and the "i*N"/"k*N" address shift ({shift} =
# log2({n})) both differ -- see this generator script's own header
# comment for why N is restricted to powers of two here (keeps the
# multiply-by-N in address computation a single `slli`, matching
# Phase 11's real, already-verified hardware timing, rather than
# introducing a software multiply that would change what's measured).

    li   x23, 0x1000
    li   x2, 0x2000
    li   x3, 0x3000
    li   x9, {n}
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF

    li   x13, 0
setup_i:
    li   x14, 0
setup_j:
    add  x15, x13, x14
    slli x16, x13, {shift}
    add  x16, x16, x14
    slli x16, x16, 2

    addi x17, x15, 1
    add  x18, x23, x16
    sw   x17, 0(x18)

    addi x17, x15, 2
    add  x18, x2, x16
    sw   x17, 0(x18)

    addi x14, x14, 1
    bne  x14, x9, setup_j
    addi x13, x13, 1
    bne  x13, x9, setup_i

    li   x13, 0
mm_i:
    li   x14, 0
mm_j:
    li   x19, 0
    li   x21, 0
mm_k:
    slli x16, x13, {shift}
    add  x16, x16, x21
    slli x16, x16, 2
    add  x18, x23, x16
    lw   x11, 0(x18)

    slli x16, x21, {shift}
    add  x16, x16, x14
    slli x16, x16, 2
    add  x18, x2, x16
    lw   x12, 0(x18)

    jal  x1, mul32
    add  x19, x19, x10

    addi x21, x21, 1
    bne  x21, x9, mm_k

    slli x16, x13, {shift}
    add  x16, x16, x14
    slli x16, x16, 2
    add  x18, x3, x16
    sw   x19, 0(x18)

    addi x14, x14, 1
    bne  x14, x9, mm_j
    addi x13, x13, 1
    bne  x13, x9, mm_i

    sw   x30, 0(x29)
    j    done

mul32:
    li   x10, 0
    mv   x5, x11
    mv   x6, x12
mul32_loop:
    beq  x6, x0, mul32_done
    andi x7, x6, 1
    beq  x7, x0, mul32_skip
    add  x10, x10, x5
mul32_skip:
    slli x5, x5, 1
    srli x6, x6, 1
    j    mul32_loop
mul32_done:
    ret

done:
    j done
"""


def gen_accel_vecadd(n):
    return f"""\
# accel_vecadd_n{n}.s -- Phase 13 scheduler dataset: accelerator-driven
# vector add, N={n}. Generated from
# sim/programs/benchmarks/accel_vecadd_bench.s's structure (Phase 11);
# only the loop bound N differs. LEN is written from the x9 register
# (already N-parameterized, not a hardcoded immediate) -- see
# accel_vecadd_bench.s.

    li   x1, 0x30000000
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF

    li   x2, 0x1000
    li   x3, 0x2000
    add  x2, x1, x2
    add  x3, x1, x3

    li   x9, {n}
    li   x4, 0
setup_loop:
    addi x5, x4, 1
    slli x6, x4, 2
    add  x7, x2, x6
    sw   x5, 0(x7)
    addi x8, x4, 2
    add  x7, x3, x6
    sw   x8, 0(x7)
    addi x4, x4, 1
    bne  x4, x9, setup_loop

    sw   x9, 8(x1)
    accel.vecadd

wait_loop:
    accel.stat x6
    andi x7, x6, 1
    bne  x7, x0, wait_loop

    sw   x30, 0(x29)
done:
    j    done
"""


def gen_accel_dot(n):
    return f"""\
# accel_dot_n{n}.s -- Phase 13 scheduler dataset: accelerator-driven
# dot product, N={n}. Generated from
# sim/programs/benchmarks/accel_dot_bench.s's structure (Phase 11);
# only the loop bound N differs.

    li   x1, 0x30000000
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF

    li   x2, 0x1000
    li   x3, 0x2000
    add  x2, x1, x2
    add  x3, x1, x3

    li   x9, {n}
    li   x4, 0
setup_loop:
    addi x5, x4, 1
    slli x6, x4, 2
    add  x7, x2, x6
    sw   x5, 0(x7)
    addi x8, x4, 2
    add  x7, x3, x6
    sw   x8, 0(x7)
    addi x4, x4, 1
    bne  x4, x9, setup_loop

    sw   x9, 8(x1)
    accel.dot

wait_loop:
    accel.stat x6
    andi x7, x6, 1
    bne  x7, x0, wait_loop

    sw   x30, 0(x29)
done:
    j    done
"""


def gen_accel_matmul(n):
    shift = int(math.log2(n))
    assert 1 << shift == n, f"matmul N={n} must be a power of 2"
    return f"""\
# accel_matmul_n{n}.s -- Phase 13 scheduler dataset: accelerator-driven
# {n}x{n} matrix multiply. Generated from
# sim/programs/benchmarks/accel_matmul_bench.s's structure (Phase 11);
# the loop bound N and the "i*N" address shift ({shift} = log2({n}))
# both differ -- see gen_cpu_matmul()'s comment for why N is
# restricted to powers of two.

    li   x1, 0x30000000
    li   x29, 0x20000000
    li   x30, 0xDEADBEEF

    li   x2, 0x1000
    li   x3, 0x2000
    add  x2, x1, x2
    add  x3, x1, x3

    li   x9, {n}

    li   x13, 0
setup_i:
    li   x14, 0
setup_j:
    add  x15, x13, x14
    slli x16, x13, {shift}
    add  x16, x16, x14
    slli x16, x16, 2

    addi x17, x15, 1
    add  x18, x2, x16
    sw   x17, 0(x18)

    addi x17, x15, 2
    add  x18, x3, x16
    sw   x17, 0(x18)

    addi x14, x14, 1
    bne  x14, x9, setup_j
    addi x13, x13, 1
    bne  x13, x9, setup_i

    sw   x9, 8(x1)
    accel.matmul

wait_loop:
    accel.stat x6
    andi x7, x6, 1
    bne  x7, x0, wait_loop

    sw   x30, 0(x29)
done:
    j    done
"""


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    written = []

    for n in VECADD_DOT_EXTRA_SIZES:
        for name, gen in [("cpu_vecadd", gen_cpu_vecadd), ("cpu_dot", gen_cpu_dot),
                           ("accel_vecadd", gen_accel_vecadd), ("accel_dot", gen_accel_dot)]:
            path = os.path.join(OUT_DIR, f"{name}_n{n}.s")
            with open(path, "w") as f:
                f.write(gen(n))
            written.append(path)

    for n in MATMUL_EXTRA_SIZES:
        for name, gen in [("cpu_matmul", gen_cpu_matmul), ("accel_matmul", gen_accel_matmul)]:
            path = os.path.join(OUT_DIR, f"{name}_n{n}.s")
            with open(path, "w") as f:
                f.write(gen(n))
            written.append(path)

    print(f"Wrote {len(written)} program(s) to {OUT_DIR}")
    for p in written:
        print(f"  {os.path.relpath(p, ROOT)}")


if __name__ == "__main__":
    main()
